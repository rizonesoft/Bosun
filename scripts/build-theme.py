#!/usr/bin/env python3
"""Generates the panel's theme resources from `design/tokens/colors.json`.

    python scripts/build-theme.py            write src/Bosun.Panel/Theme/Generated/Dark.xaml and Light.xaml
    python scripts/build-theme.py --check    exit 1 naming each generated file that is missing or differs

Each theme gets, in the token file's order, a `Color` `C.<name>` and a frozen `SolidColorBrush` `B.<name>` for every
colour, a `CornerRadius` `R.<name>` for every radius, and a `sys:Double` `S.<name>` for every space and `T.<name>` for
every type size: the key names Steward's theme uses, so its control templates port unchanged. Then (D02 T03 §1) a
frozen `DropShadowEffect` `Elevation.<name>` for every elevation, at that theme's opacity, and the motion: a `Duration`
`Motion.<name>` for every `<name>Ms` and a frozen `KeySpline` `Motion.Ease`, the same in both themes. Edit the tokens,
never the generated XAML: `--check` in `scripts/check-all.ps1` fails a hand edit. An eight-digit colour is alpha first
(#AARRGGBB), as WPF reads it, so colours pass through unchanged.

    python scripts/build-theme.py --tokens <colors.json> --out <folder> [--check]

reads and writes elsewhere, for the tests. Exit 0 done, 1 a generated file differs (`--check`), 2 a token is bad,
named by its path (`dark.TextDim`), with nothing written, 3 a generated file couldn't be written, with what was
updated and what was left as it was said.
"""
import argparse
import json
import os
from pathlib import Path
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "design" / "tokens" / "colors.json"
OUT = ROOT / "src" / "Bosun.Panel" / "Theme" / "Generated"
THEMES = ("dark", "light")
# The keys the panel's consumers use: a token file without one of them is refused, even when both themes lack it.
REQUIRED = {
    "colours": ("Base", "Surface", "Raised", "Hover", "Line", "Text", "TextDim", "TextMute", "Accent", "AccentDim",
                "OnAccent", "Ok", "Warn", "Danger", "Info", "LineStrong", "OkSoft", "WarnSoft", "DangerSoft", "InfoSoft"),
    "radius": ("Card", "Control", "Sheet", "Overlay", "Pill"),
    "size": ("Form",),
    "space": ("XS", "S", "M", "L", "XL"),
    "type": ("Caption", "Body", "Subtitle", "Title", "Metric"),
    "elevation": ("Card", "Overlay"),
    "motion": ("FastMs", "NormalMs", "SlowMs", "PulseMs"),
}
# What an elevation holds: its measures, and its opacity in each theme.
ELEVATION = ("Blur", "Depth", "OpacityDark", "OpacityLight")
OPACITY = {"dark": "OpacityDark", "light": "OpacityLight"}
MAX_MS = 10000
# Group -> (key prefix, XAML element) for the measures.
MEASURES = (("radius", "R", "CornerRadius"), ("size", "Size", "sys:Double"), ("space", "S", "sys:Double"), ("type", "T", "sys:Double"))
COLOUR = re.compile(r"#(?:[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})")
NAME = re.compile(r"[A-Za-z][A-Za-z0-9]*")
HEADER = "<!-- Generated by scripts/build-theme.py from design/tokens/colors.json. Do not edit: change the tokens and run the script. -->"


class TokenError(Exception):
    """A bad token, named by its path in the token file."""


def group(tokens: dict, name: str) -> dict:
    value = tokens.get(name)
    if value is None:
        raise TokenError(f"{name}: missing")
    if not isinstance(value, dict):
        raise TokenError(f"{name}: must be an object")
    if not value:
        raise TokenError(f"{name}: is empty")
    for key in value:
        if not NAME.fullmatch(key):  # fullmatch: `$` with match() lets a trailing newline through
            raise TokenError(f"{name}.{key}: a token name is letters and digits, starting with a letter")
    return value


def number(path: str, value) -> str:
    # bool is an int in Python, and no measure is a yes or no.
    # The bounds come before anything turns the value into a float: an integer of 400 digits is a valid JSON number,
    # and math.isfinite raises OverflowError on it. Comparing never does, and NaN fails the comparison.
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not 0 <= value <= 1000:
        raise TokenError(f"{path}: must be a number from 0 to 1000")
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def fraction(path: str, value) -> str:
    """A number from 0 to 1: an opacity, or a point of an easing curve."""
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not 0 <= value <= 1:
        raise TokenError(f"{path}: must be a number from 0 to 1")
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def milliseconds(path: str, value) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or not 0 <= value <= MAX_MS:
        raise TokenError(f"{path}: must be a whole number of milliseconds from 0 to {MAX_MS}")
    return value


def duration(ms: int) -> str:
    """A WPF Duration of a whole number of milliseconds: 120 is 0:0:0.120."""
    return f"0:0:{ms // 1000}.{ms % 1000:03d}"


def check_elevation(elevation: dict) -> None:
    for key in REQUIRED["elevation"]:
        if key not in elevation:
            raise TokenError(f"elevation.{key}: missing")
    for key, value in elevation.items():
        if not isinstance(value, dict):
            raise TokenError(f"elevation.{key}: must be an object")
        for part in ELEVATION:
            if part not in value:
                raise TokenError(f"elevation.{key}.{part}: missing")
        for part in value:
            if part not in ELEVATION:
                raise TokenError(f"elevation.{key}.{part}: not an elevation's part ({', '.join(ELEVATION)})")
        number(f"elevation.{key}.Blur", value["Blur"])
        number(f"elevation.{key}.Depth", value["Depth"])
        for theme in THEMES:
            fraction(f"elevation.{key}.{OPACITY[theme]}", value[OPACITY[theme]])


def check_motion(motion: dict) -> None:
    for key in REQUIRED["motion"]:
        if key not in motion:
            raise TokenError(f"motion.{key}: missing")
    if "Ease" not in motion:
        raise TokenError("motion.Ease: missing")
    for key, value in motion.items():
        if key == "Ease":
            # A cubic Bezier's two control points (x1, y1, x2, y2); WPF's KeySpline takes each coordinate from 0 to 1.
            if not isinstance(value, list) or len(value) != 4:
                raise TokenError("motion.Ease: must be four numbers, x1, y1, x2, y2")
            for index, point in enumerate(value):
                fraction(f"motion.Ease[{index}]", point)
        elif key.endswith("Ms") and len(key) > 2:
            # The duration is emitted as Motion.<name>: Ease is the easing's key, so EaseMs would be a second
            # Motion.Ease and a dictionary WPF refuses to load.
            if key[:-2] == "Ease":
                raise TokenError("motion.EaseMs: Motion.Ease is the easing's key; name the duration otherwise")
            milliseconds(f"motion.{key}", value)
        else:
            raise TokenError(f"motion.{key}: a motion token is a duration named <name>Ms, or Ease")


def validate(tokens) -> dict:
    """Every token checked before anything is written; returns the groups."""
    if not isinstance(tokens, dict):
        raise TokenError("the token file: must be a JSON object")
    groups = {name: group(tokens, name) for name in THEMES + ("radius", "size", "space", "type", "elevation", "motion")}
    for theme in THEMES:
        other = THEMES[1 - THEMES.index(theme)]
        for key in groups[theme]:
            if key not in groups[other]:
                raise TokenError(f"{other}.{key}: missing (it is in {theme})")
        for key in REQUIRED["colours"]:
            if key not in groups[theme]:
                raise TokenError(f"{theme}.{key}: missing")
        for key, value in groups[theme].items():
            if not isinstance(value, str) or not COLOUR.fullmatch(value):
                raise TokenError(f"{theme}.{key}: must be #RRGGBB or #AARRGGBB")
    for name, _, _ in MEASURES:
        for key in REQUIRED[name]:
            if key not in groups[name]:
                raise TokenError(f"{name}.{key}: missing")
        for key, value in groups[name].items():
            number(f"{name}.{key}", value)
    check_elevation(groups["elevation"])
    check_motion(groups["motion"])
    return groups


def render(groups: dict, theme: str) -> str:
    lines = [
        HEADER,
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
        '                    xmlns:sys="clr-namespace:System;assembly=System.Runtime"',
        # Not marked ignorable: WPF's reader skips an mc:Ignorable namespace, which leaves the brushes unfrozen.
        '                    xmlns:po="http://schemas.microsoft.com/winfx/2006/xaml/presentation/options">',
        "",
        "    <!-- Colours -->",
    ]
    colours = groups[theme]
    for key, value in colours.items():
        lines.append(f'    <Color x:Key="C.{key}">{value.upper()}</Color>')
    lines += ["", "    <!-- Brushes, frozen: they never change, so WPF can share them across threads and skip change tracking -->"]
    for key in colours:
        lines.append(f'    <SolidColorBrush x:Key="B.{key}" Color="{{StaticResource C.{key}}}" po:Freeze="True"/>')
    titles = {"radius": "Corner radii", "size": "Sizes: a settings form's readable width", "space": "Spacing", "type": "Type sizes"}
    for name, prefix, element in MEASURES:
        lines += ["", f"    <!-- {titles[name]} -->"]
        for key, value in groups[name].items():
            lines.append(f'    <{element} x:Key="{prefix}.{key}">{number(f"{name}.{key}", value)}</{element}>')
    # The space scale as margins too (D02 T04 §2): a Margin takes a Thickness, never a number, so a gap below or above
    # a label or a section is named from the same scale instead of typed.
    lines += ["", "    <!-- Gaps: the space scale as a margin below or above an element -->"]
    for key, value in groups["space"].items():
        v = number(f"space.{key}", value)
        lines.append(f'    <Thickness x:Key="Gap.Below.{key}">0,0,0,{v}</Thickness>')
        lines.append(f'    <Thickness x:Key="Gap.Above.{key}">0,{v},0,0</Thickness>')
        # And the same space all round: a card's or a panel's padding (D02 T04 §3).
        lines.append(f'    <Thickness x:Key="Inset.{key}">{v}</Thickness>')
        lines.append(f'    <Thickness x:Key="Gap.Before.{key}">{v},0,0,0</Thickness>')
        lines.append(f'    <Thickness x:Key="Gap.After.{key}">0,0,{v},0</Thickness>')
        # A table bleeds its cells' leading space into its card, so its text still starts at the card's edge (D02 T04 §4).
        lines.append(f'    <Thickness x:Key="Bleed.Before.{key}">-{v},0,0,0</Thickness>')
    # A table cell's padding: XS before its text, clear of an inside focus ring, and M after it to the next column.
    space = groups["space"]
    lines.append(f'    <Thickness x:Key="Cell.Pad">{number("space.XS", space["XS"])},0,{number("space.M", space["M"])},0</Thickness>')
    lines += ["", "    <!-- Elevation: a shadow straight down, black, at this theme's opacity; frozen, so it is shared and never re-tracked -->"]
    for key, value in groups["elevation"].items():
        lines.append(f'    <DropShadowEffect x:Key="Elevation.{key}" BlurRadius="{number(f"elevation.{key}.Blur", value["Blur"])}" '
                     f'ShadowDepth="{number(f"elevation.{key}.Depth", value["Depth"])}" Direction="270" Color="#FF000000" '
                     f'Opacity="{fraction(f"elevation.{key}.{OPACITY[theme]}", value[OPACITY[theme]])}" po:Freeze="True"/>')
    lines += ["", "    <!-- Motion: the design's durations and easing. Read through Theme/Motion.cs, which gives zero when Windows' animation effects are off -->"]
    motion = groups["motion"]
    for key, value in motion.items():
        if key != "Ease":
            lines.append(f'    <Duration x:Key="Motion.{key[:-2]}">{duration(value)}</Duration>')
    x1, y1, x2, y2 = (fraction(f"motion.Ease[{i}]", v) for i, v in enumerate(motion["Ease"]))
    lines.append(f'    <KeySpline x:Key="Motion.Ease" ControlPoint1="{x1},{y1}" ControlPoint2="{x2},{y2}" po:Freeze="True"/>')
    lines += ["</ResourceDictionary>", ""]
    return "\n".join(lines)


def discard(temp: str) -> None:
    try:
        os.unlink(temp)
    except OSError:
        pass  # already gone, or held: a stray temporary file changes nothing a reader sees


def write_outputs(outputs: dict) -> int:
    """Writes every generated file, or says exactly what happened. Each is staged as a temporary file beside its
    target first, so a full disk or a denied folder fails before anything is changed; then each is moved over its
    target. A move that fails (a file held open) leaves that file as it was, the temporary files are removed, and the
    report names what was updated and what wasn't. Returns 0, or 3 when an output couldn't be written."""
    staged = []  # (temporary file, target)
    try:
        for path, text in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            fd, temp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
            staged.append((temp, path))
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    except OSError as e:
        for temp, _ in staged:
            discard(temp)
        print(f"build-theme: can't write the generated theme ({e}); nothing was changed", file=sys.stderr)
        return 3
    done = []
    for index, (temp, path) in enumerate(staged):
        try:
            os.replace(temp, path)
            done.append(path)
        except OSError as e:
            for other, _ in staged[index:]:
                discard(other)
            left = [str(p) for _, p in staged[index:]]
            print(f"build-theme: can't replace {path} ({e}). Updated: {', '.join(map(str, done)) or 'nothing'}. "
                  f"Left as they were: {', '.join(left)}. Close whatever holds the file and run the script again; "
                  "--check fails until it has.", file=sys.stderr)
            return 3
    return 0


def same(path: Path, text: str) -> bool:
    try:
        on_disk = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):  # missing or not text: it differs
        return False
    return on_disk.replace("\r\n", "\n") == text


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Generates the panel's theme resources from design/tokens/colors.json.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if a generated file differs")
    parser.add_argument("--tokens", type=Path, default=TOKENS, help="the token file (default design/tokens/colors.json)")
    parser.add_argument("--out", type=Path, default=OUT, help="the folder for Dark.xaml and Light.xaml")
    args = parser.parse_args(argv)
    try:
        try:
            tokens = json.loads(args.tokens.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError) as e:
            raise TokenError(f"the token file: can't be read ({e})")
        except json.JSONDecodeError as e:
            raise TokenError(f"the token file: not JSON ({e})")
        groups = validate(tokens)
    except TokenError as e:
        print(f"build-theme: {e}; nothing was written", file=sys.stderr)
        return 2
    outputs = {args.out / f"{theme.capitalize()}.xaml": render(groups, theme) for theme in THEMES}
    if args.check:
        stale = [path for path, text in outputs.items() if not same(path, text)]
        for path in stale:
            print(f"build-theme: {path} is missing or differs from the tokens: run python scripts/build-theme.py", file=sys.stderr)
        return 1 if stale else 0
    return write_outputs(outputs)


if __name__ == "__main__":
    sys.exit(main())
