#!/usr/bin/env python3
"""Generates the panel's theme resources from `design/tokens/colors.json`.

    python scripts/build-theme.py            write src/Bosun.Panel/Theme/Generated/Dark.xaml and Light.xaml
    python scripts/build-theme.py --check    exit 1 naming each generated file that is missing or differs

Each theme gets, in the token file's order, a `Color` `C.<name>` and a frozen `SolidColorBrush` `B.<name>` for every
colour, a `CornerRadius` `R.<name>` for every radius, and a `sys:Double` `S.<name>` for every space and `T.<name>` for
every type size: the key names Steward's theme uses, so its control templates port unchanged. Elevation and motion
are emitted by D02 T03 §1. Edit the tokens, never the generated XAML: `--check` in `scripts/check-all.ps1` fails a
hand edit. An eight-digit colour is alpha first (#AARRGGBB), as WPF reads it, so colours pass through unchanged.

    python scripts/build-theme.py --tokens <colors.json> --out <folder> [--check]

reads and writes elsewhere, for the tests. Exit 0 done, 1 a generated file differs (`--check`), 2 a token is bad,
named by its path (`dark.TextDim`), with nothing written.
"""
import argparse
import json
import math
import os
from pathlib import Path
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "design" / "tokens" / "colors.json"
OUT = ROOT / "src" / "Bosun.Panel" / "Theme" / "Generated"
THEMES = ("dark", "light")
# The keys the panel's consumers use: a token file without one of them is refused, even when both themes lack it.
REQUIRED = {
    "colours": ("Base", "Surface", "Raised", "Hover", "Line", "Text", "TextDim", "TextMute", "Accent", "AccentDim",
                "OnAccent", "Ok", "Warn", "Danger", "Info", "LineStrong", "OkSoft", "WarnSoft", "DangerSoft", "InfoSoft"),
    "radius": ("Card", "Control", "Sheet", "Overlay", "Pill"),
    "space": ("XS", "S", "M", "L", "XL"),
    "type": ("Caption", "Body", "Subtitle", "Title", "Metric"),
}
# Group -> (key prefix, XAML element) for the measures.
MEASURES = (("radius", "R", "CornerRadius"), ("space", "S", "sys:Double"), ("type", "T", "sys:Double"))
COLOUR = re.compile(r"^#(?:[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$")
NAME = re.compile(r"^[A-Za-z][A-Za-z0-9]*$")
HEADER = "<!-- Generated by scripts/build-theme.py from design/tokens/colors.json. Do not edit: change the tokens and run the script. -->"


class TokenError(Exception):
    """A bad token, named by its path in the token file."""


def group(tokens: dict, name: str) -> dict:
    value = tokens.get(name)
    if value is None:
        raise TokenError(f"{name}: missing")
    if not isinstance(value, dict):
        raise TokenError(f"{name}: must be an object")
    if not value:
        raise TokenError(f"{name}: is empty")
    for key in value:
        if not NAME.match(key):
            raise TokenError(f"{name}.{key}: a token name is letters and digits, starting with a letter")
    return value


def number(path: str, value) -> str:
    # bool is an int in Python, and no measure is a yes or no.
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value) or not 0 <= value <= 1000:
        raise TokenError(f"{path}: must be a number from 0 to 1000")
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def validate(tokens) -> dict:
    """Every token checked before anything is written; returns the groups."""
    if not isinstance(tokens, dict):
        raise TokenError("the token file: must be a JSON object")
    groups = {name: group(tokens, name) for name in THEMES + ("radius", "space", "type")}
    for theme in THEMES:
        other = THEMES[1 - THEMES.index(theme)]
        for key in groups[theme]:
            if key not in groups[other]:
                raise TokenError(f"{other}.{key}: missing (it is in {theme})")
        for key in REQUIRED["colours"]:
            if key not in groups[theme]:
                raise TokenError(f"{theme}.{key}: missing")
        for key, value in groups[theme].items():
            if not isinstance(value, str) or not COLOUR.match(value):
                raise TokenError(f"{theme}.{key}: must be #RRGGBB or #AARRGGBB")
    for name, _, _ in MEASURES:
        for key in REQUIRED[name]:
            if key not in groups[name]:
                raise TokenError(f"{name}.{key}: missing")
        for key, value in groups[name].items():
            number(f"{name}.{key}", value)
    return groups


def render(groups: dict, theme: str) -> str:
    lines = [
        HEADER,
        '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
        '                    xmlns:sys="clr-namespace:System;assembly=System.Runtime"',
        # Not marked ignorable: WPF's reader skips an mc:Ignorable namespace, which leaves the brushes unfrozen.
        '                    xmlns:po="http://schemas.microsoft.com/winfx/2006/xaml/presentation/options">',
        "",
        "    <!-- Colours -->",
    ]
    colours = groups[theme]
    for key, value in colours.items():
        lines.append(f'    <Color x:Key="C.{key}">{value.upper()}</Color>')
    lines += ["", "    <!-- Brushes, frozen: they never change, so WPF can share them across threads and skip change tracking -->"]
    for key in colours:
        lines.append(f'    <SolidColorBrush x:Key="B.{key}" Color="{{StaticResource C.{key}}}" po:Freeze="True"/>')
    titles = {"radius": "Corner radii", "space": "Spacing", "type": "Type sizes"}
    for name, prefix, element in MEASURES:
        lines += ["", f"    <!-- {titles[name]} -->"]
        for key, value in groups[name].items():
            lines.append(f'    <{element} x:Key="{prefix}.{key}">{number(f"{name}.{key}", value)}</{element}>')
    lines += ["</ResourceDictionary>", ""]
    return "\n".join(lines)


def write_atomically(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.replace(temp, path)
    except BaseException:
        try:
            os.unlink(temp)
        except OSError:
            pass
        raise


def same(path: Path, text: str) -> bool:
    try:
        on_disk = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):  # missing or not text: it differs
        return False
    return on_disk.replace("\r\n", "\n") == text


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Generates the panel's theme resources from design/tokens/colors.json.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if a generated file differs")
    parser.add_argument("--tokens", type=Path, default=TOKENS, help="the token file (default design/tokens/colors.json)")
    parser.add_argument("--out", type=Path, default=OUT, help="the folder for Dark.xaml and Light.xaml")
    args = parser.parse_args(argv)
    try:
        try:
            tokens = json.loads(args.tokens.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError) as e:
            raise TokenError(f"the token file: can't be read ({e})")
        except json.JSONDecodeError as e:
            raise TokenError(f"the token file: not JSON ({e})")
        groups = validate(tokens)
    except TokenError as e:
        print(f"build-theme: {e}; nothing was written", file=sys.stderr)
        return 2
    outputs = {args.out / f"{theme.capitalize()}.xaml": render(groups, theme) for theme in THEMES}
    if args.check:
        stale = [path for path, text in outputs.items() if not same(path, text)]
        for path in stale:
            print(f"build-theme: {path} is missing or differs from the tokens: run python scripts/build-theme.py", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        write_atomically(path, text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
